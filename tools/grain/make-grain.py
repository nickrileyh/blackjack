#!/usr/bin/env python3
"""Writes src/grain.js: the fine dither laid over the whole app so gradients don't show steps.

A screen has 256 levels of each colour. A soft gradient on a dark surface only crosses a handful of them, so it is
drawn as a few flat bands with visible edges (rings round a glow, stripes down a card). A dither hides the edges: a
tile of very faint specks, lighter ones and darker ones, each worth only a level or two. The tile is "blue" noise
(white noise with its slow ripples filtered out, so it has no blotches and no pattern the eye can pick up), and it
wraps, so it tiles with no seam.

Needs numpy and Pillow. Run it, then ./build.sh. Change LIGHT / DARK to make the grain stronger or weaker."""
import base64, io, os
import numpy as np
from PIL import Image

N = 128        # tile size in device pixels
LIGHT = 5      # strongest light speck, out of 255 (what dithers the dark themes)
DARK = 3       # strongest dark speck, out of 255 (what dithers the light themes)

rng = np.random.default_rng(21)
w = rng.standard_normal((N, N))
fy, fx = np.meshgrid(np.fft.fftfreq(N), np.fft.fftfreq(N), indexing="ij")
f = np.sqrt(fx * fx + fy * fy)
blue = np.real(np.fft.ifft2(np.fft.fft2(w) * np.minimum(1, f / 0.22) ** 1.5))    # drop the slow ripples
rank = blue.ravel().argsort().argsort().reshape(N, N) / (N * N - 1)                # even spread from 0 to 1

# 0 .. DARK-1 are black specks (strongest first), DARK is clear, DARK+1 .. are white specks
idx = np.where(rank < 0.5, np.floor(rank * 2 * (DARK + 1)), DARK + np.minimum(LIGHT, np.floor((rank - 0.5) * 2 * (LIGHT + 1)))).astype(np.uint8)
pal, alpha = [], []
for a in range(DARK, 0, -1): pal += [0, 0, 0]; alpha.append(a)
pal += [0, 0, 0]; alpha.append(0)
for a in range(1, LIGHT + 1): pal += [255, 255, 255]; alpha.append(a)
im = Image.fromarray(idx, "P"); im.putpalette(pal + [0] * (768 - len(pal)))
buf = io.BytesIO(); im.save(buf, "PNG", optimize=True, transparency=bytes(alpha))
uri = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
out = os.path.join(os.path.dirname(__file__), "..", "..", "src", "grain.js")
open(out, "w").write("// Generated by tools/grain/make-grain.py — do not edit by hand.\nexport const GRAIN = \"" + uri + "\";\n")
print(len(buf.getvalue()), "bytes of PNG ->", os.path.normpath(out))
