#!/usr/bin/env python3
"""Builds src/sound-data.js: the recorded card, chip and shuffle sounds, as small MP3 clips in base64.

    python3 tools/sounds/build-sounds.py        (needs ffmpeg and numpy)

The recordings are from Kenney's "Casino Audio" pack (CC0, kenney.nl) — see kenney/License.txt.
Each clip is cut to the sound itself, given short fades, and levelled so the clips in one group are equally loud.
To change which recordings are used, edit CLIPS below and run this again, then ./build.sh.
"""
import base64, os, subprocess, tempfile, wave
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SR = 44100
# group -> [(file, start seconds or None for "where the sound starts", end seconds or None for "where it stops")]
CLIPS = {
    "card": [("card-slide-1", None, None), ("card-slide-2", None, None), ("card-slide-4", None, None), ("card-slide-5", None, None), ("card-slide-6", None, None)],
    "chip": [("chip-lay-1", None, None), ("chip-lay-2", None, None), ("chips-stack-4", None, None), ("chips-stack-5", None, None)],
    # the recording is seven shuffling strokes over three seconds; the first four are plenty
    "shuffle": [("card-shuffle", 0.06, 1.72)],
}

def decode(name):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, "a.wav")
        subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", os.path.join(HERE, "kenney", name + ".ogg"), "-ac", "1", "-ar", str(SR), out], check=True)
        w = wave.open(out); return np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float64) / 32768

def cut(x, a, b):
    pk = np.abs(x).max(); idx = np.where(np.abs(x) > max(0.02 * pk, 0.003))[0]
    i0 = int(a * SR) if a is not None else max(0, idx[0] - int(0.004 * SR))
    i1 = int(b * SR) if b is not None else min(len(x), idx[-1] + int(0.05 * SR))
    y = x[i0:i1].copy()
    fi, fo = int(0.003 * SR), int((0.07 if b is not None else 0.03) * SR)
    y[:fi] *= np.linspace(0, 1, fi); y[-fo:] *= np.linspace(1, 0, fo) ** 2
    return y

def mp3(y):
    with tempfile.TemporaryDirectory() as d:
        wav, out = os.path.join(d, "a.wav"), os.path.join(d, "a.mp3")
        w = wave.open(wav, "wb"); w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(y, -1, 1) * 32767).astype(np.int16).tobytes()); w.close()
        subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", wav, "-c:a", "libmp3lame", "-b:a", "96k", "-ac", "1", out], check=True)
        return open(out, "rb").read()

lines, total = [], 0
for group, items in CLIPS.items():
    clips = [cut(decode(n), a, b) for n, a, b in items]
    loud = [np.sqrt(np.mean(np.sort(c ** 2)[-int(0.05 * SR):])) for c in clips]           # loudness of each clip's loudest 50 ms
    target = min(loud)
    clips = [c * (target / l) for c, l in zip(clips, loud)]
    k = 0.89 / max(np.abs(c).max() for c in clips)                                         # as loud as the group allows without clipping
    enc = [mp3(c * k) for c in clips]
    total += sum(len(e) for e in enc)
    print(f"{group}: " + ", ".join(f"{n} {len(c) / SR * 1000:.0f} ms" for (n, _, _), c in zip(items, clips)))
    lines.append(f'  {group}: [\n' + ",\n".join(f'    "{base64.b64encode(e).decode()}"' for e in enc) + "\n  ],")
open(os.path.join(HERE, "..", "..", "src", "sound-data.js"), "w").write(
    "// Generated by tools/sounds/build-sounds.py — do not edit by hand.\n"
    "// Recorded card, chip and shuffle sounds from Kenney's \"Casino Audio\" pack (CC0, kenney.nl), as MP3 in base64.\n"
    "export const CLIPS = {\n" + "\n".join(lines) + "\n};\n")
print(f"src/sound-data.js: {total / 1024:.1f} KB of MP3")
